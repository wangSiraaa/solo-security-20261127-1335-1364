# --------------------------------------------------------------------------- #
# Self-test / parameter sanity check
# --------------------------------------------------------------------------- #
def _self_test() -> None:
    assert P.bit_length() == 2048, P.bit_length()
    assert Q == (P - 1) // 2
    assert pow(G, Q, P) == 1 and G != 1
    sk = PrivateKey.generate()
    payload = {"hello": "world", "n": 7}
    sig = sk.sign("test", payload)
    assert verify(sk.public, "test", payload, sig)
    assert not verify(sk.public, "test", {"hello": "world", "n": 8}, sig)
    other = PrivateKey.generate()
    assert not verify(other.public, "test", payload, sig)
    print("crypto self-test ok; group bits:", P.bit_length())


if __name__ == "__main__":  # pragma: no cover
    _self_test()
