"""Minimal self-contained asymmetric signatures for the offline festival wallet.

Everything here is pure standard library.  Signatures are Schnorr signatures in a
prime-order subgroup of a 2048-bit safe-prime group (RFC 3526, group 14).  We use
the subgroup of quadratic residues, generated by ``G = 4``, whose order is the
2048-bit prime ``Q = (P - 1) // 2``.

The point of having real asymmetric keys (rather than HMACs) is that the desk,
the door, the pre-issue authority and the local proof service each hold a private
key while every other party only needs the matching public key.  A verifier can
therefore never mint what it is supposed to check.
"""

from __future__ import annotations

import hashlib
import json
import secrets
from dataclasses import dataclass
from typing import Any, Optional

# RFC 3526, 2048-bit MODP group (group 14).
_P_HEX = (
    "FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD1"
    "29024E088A67CC74020BBEA63B139B22514A08798E3404DD"
    "EF9519B3CD3A431B302B0A6DF25F14374FE1356D6D51C245"
    "E485B576625E7EC6F44C42E9A637ED6B0BFF5CB6F406B7ED"
    "EE386BFB5A899FA5AE9F24117C4B1FE649286651ECE45B3D"
    "C2007CB8A163BF0598DA48361C55D39A69163FA8FD24CF5F"
    "83655D23DCA3AD961C62F356208552BB9ED529077096966D"
    "670C354E4ABC9804F1746C08CA18217C32905E462E36CE3B"
    "E39E772C180E86039B2783A2EC07A28FB5C55DF06F4C52C9"
    "DE2BCBF6955817183995497CEA956AE515D2261898FA0510"
    "15728E5A8AACAA68FFFFFFFFFFFFFFFF"
)

P = int(_P_HEX, 16)
Q = (P - 1) // 2
G = 4  # a quadratic residue, hence of order Q
PK_BYTES = (P.bit_length() + 7) // 8  # 256 bytes

# A second independent generator for Pedersen commitments.  We derive it by
# squaring a hash (so it lands in the order-Q subgroup) and deliberately throw
# away the exponent relative to G: nobody should know log_G(H), otherwise the
# commitments would lose their hiding property.
H_COMMIT = pow(int.from_bytes(hashlib.sha256(b"festival/H-commit/v1").digest(), "big"), 2, P)


def commit(day_number: int, blinding: int) -> int:
    """Pedersen commitment C = G^value * H^blinding (mod P)."""
    return (pow(G, day_number, P) * pow(H_COMMIT, blinding, P)) % P


# --------------------------------------------------------------------------- #
# Small helpers
# --------------------------------------------------------------------------- #
def canonical_bytes(obj: Any) -> bytes:
    """Deterministic JSON encoding used for every signed payload."""
    return json.dumps(
        obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def rand_scalar() -> int:
    """Uniform-ish non-zero scalar modulo Q."""
    return secrets.randbelow(Q - 1) + 1


def _mod_hash(*parts: bytes) -> int:
    h = hashlib.sha256()
    for p in parts:
        h.update(len(p).to_bytes(4, "big"))
        h.update(p)
    return int.from_bytes(h.digest() * 8, "big") % Q


def _challenge(R: int, msg_digest: bytes) -> int:
    return _mod_hash(b"festival/schnorr/challenge/v1", R.to_bytes(PK_BYTES, "big"), msg_digest)


def _message_digest(domain: str, payload: Any) -> bytes:
    if isinstance(payload, (dict, list)):
        body = canonical_bytes(payload)
    elif isinstance(payload, bytes):
        body = payload
    else:
        body = str(payload).encode("utf-8")
    return sha256(b"festival/schnorr/msg/v1\x00" + domain.encode("utf-8") + b"\x00" + body)


# --------------------------------------------------------------------------- #
# Keys
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class PublicKey:
    value: int

    @property
    def hex(self) -> str:
        return format(self.value, "x")

    @classmethod
    def from_hex(cls, s: str) -> "PublicKey":
        return cls(int(s, 16))

    def __str__(self) -> str:  # pragma: no cover - cosmetic
        return self.hex


class PrivateKey:
    """A Schnorr private key; only the holder should ever see ``secret``."""

    def __init__(self, secret: int):
        if not (1 <= secret < Q):
            raise ValueError("secret scalar out of range")
        self.secret = secret
        self.public = PublicKey(pow(G, secret, P))

    @classmethod
    def generate(cls) -> "PrivateKey":
        return cls(rand_scalar())

    @classmethod
    def derive(cls, domain: str, material: bytes) -> "PrivateKey":
        """Deterministically derive a key (used for per-program pseudonyms)."""
        sk = _mod_hash(b"festival/derive/v1", domain.encode(), material)
        if sk == 0:
            raise ValueError("degenerate derived key")
        return cls(sk)

    # -- signing ---------------------------------------------------------- #
    def sign(self, domain: str, payload: Any) -> dict:
        msg = _message_digest(domain, payload)
        k = rand_scalar()
        R = pow(G, k, P)
        e = _challenge(R, msg)
        s = (k + self.secret * e) % Q
        return {"R": format(R, "x"), "s": format(s, "x")}

    def sign_payload(self, domain: str, payload: Any) -> dict:
        """Return a copy of ``payload`` with an attached ``sig`` field."""
        signed = dict(payload)
        signed["sig"] = self.sign(domain, payload)
        return signed


def verify(public: PublicKey, domain: str, payload: Any, signature: Optional[dict]) -> bool:
    """Verify a Schnorr signature.  ``payload`` must be the dict without ``sig``."""
    if not signature or "R" not in signature or "s" not in signature:
        return False
    try:
        R = int(signature["R"], 16)
        s = int(signature["s"], 16)
    except (ValueError, TypeError):
        return False
    if not (0 < R < P) or not (0 <= s < Q):
        return False
    msg = _message_digest(domain, payload)
    e = _challenge(R, msg)
    lhs = pow(G, s, P)
    rhs = (R * pow(public.value, e, P)) % P
    return lhs == rhs


def strip_sig(payload: dict) -> dict:
    return {k: v for k, v in payload.items() if k != "sig"}


